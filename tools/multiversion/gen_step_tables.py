#!/usr/bin/env python3
"""Generate the id tables for one multiversion step (an older server version
`OLD` played by this client's version `NEW`) from two data generator runs.

Each run is a folder holding the version's server jar (`server.jar`) and the
reports it generated:

    java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports

Usage: gen_step_tables.py OLD_DIR NEW_DIR OUT.rs

The output is Rust source for `horizon-multiversion`: packet id tables per
state, registry id tables (old id -> new id), the tags the new version has
that the old one lacks (with their resolved new ids) and named ids the step
code refers to.
"""
import io
import json
import os
import sys
import zipfile

old_dir, new_dir, out_path = sys.argv[1:4]


def report(base, name):
    with open(os.path.join(base, 'generated', 'reports', name), encoding='utf-8') as f:
        return json.load(f)


def inner_jar(base):
    """The bundled server jar inside a bundler jar."""
    outer = zipfile.ZipFile(os.path.join(base, 'server.jar'))
    for name in outer.namelist():
        if name.startswith('META-INF/versions/') and name.endswith('.jar'):
            return zipfile.ZipFile(io.BytesIO(outer.read(name)))
    return outer


def ident(name):
    return name.split(':', 1)[1] if name.startswith('minecraft:') else name


def const(name):
    return ident(name).upper().replace('/', '_').replace('.', '_').replace('-', '_')


packets_old, packets_new = report(old_dir, 'packets.json'), report(new_dir, 'packets.json')
registries_old, registries_new = report(old_dir, 'registries.json'), report(new_dir, 'registries.json')
blocks_old, blocks_new = report(old_dir, 'blocks.json'), report(new_dir, 'blocks.json')

out = []
w = out.append
w('//! Id tables for this step. Generated by tools/multiversion/gen_step_tables.py')
w('//! from the data generator reports of both versions; do not edit by hand.')
w('#![allow(dead_code, clippy::unreadable_literal)]')
w('')


def packet_ids(packets, state, direction):
    entries = packets.get(state, {}).get(direction, {})
    return {ident(k): v['protocol_id'] for k, v in entries.items()}


def emit_ids(mod, ids):
    w(f'pub mod {mod} {{')
    for name, i in sorted(ids.items(), key=lambda e: e[1]):
        w(f'    pub const {const(name)}: i32 = {i};')
    w('}')


# Packet ids. A table maps the sender's ids to the receiver's: clientbound
# old -> new, serverbound new -> old; -1 where the receiver has no such packet.
w('pub mod packets {')
for state in ('configuration', 'play', 'login', 'status', 'handshake'):
    for direction in ('clientbound', 'serverbound'):
        o, n = packet_ids(packets_old, state, direction), packet_ids(packets_new, state, direction)
        if not o and not n:
            continue
        src, dst = (o, n) if direction == 'clientbound' else (n, o)
        table = [-1] * (max(src.values()) + 1 if src else 0)
        for name, i in src.items():
            table[i] = dst.get(name, -1)
        identical = all(table[i] == i for i in range(len(table))) and len(o) == len(n)
        mod = f'{state}_{direction}'
        w(f'    pub mod {mod} {{')
        w(f'        /// The ids are the same in both versions.')
        w(f'        pub const IDENTICAL: bool = {"true" if identical else "false"};')
        w(f'        pub static MAP: [i16; {len(table)}] = {table};')
        for label, ids in (('old', o), ('new', n)):
            w(f'        pub mod {label} {{')
            for name, i in sorted(ids.items(), key=lambda e: e[1]):
                w(f'            pub const {const(name)}: i32 = {i};')
            w('        }')
        w('    }')
w('}')
w('')

# Builtin registries whose ids changed, old id -> new id. Entries the new
# version removed map to `fallback` (the registry's default when it has one).
REMAPPED = {
    'minecraft:item': 'ITEMS',
    'minecraft:block': 'BLOCKS',
    'minecraft:entity_type': 'ENTITY_TYPES',
    'minecraft:sound_event': 'SOUNDS',
    'minecraft:particle_type': 'PARTICLES',
    'minecraft:data_component_type': 'DATA_COMPONENTS',
    'minecraft:custom_stat': 'CUSTOM_STATS',
    'minecraft:command_argument_type': 'ARGUMENT_TYPES',
    'minecraft:menu': 'MENUS',
    'minecraft:mob_effect': 'MOB_EFFECTS',
    'minecraft:attribute': 'ATTRIBUTES',
    'minecraft:block_entity_type': 'BLOCK_ENTITY_TYPES',
    'minecraft:fluid': 'FLUIDS',
    'minecraft:game_event': 'GAME_EVENTS',
    'minecraft:stat_type': 'STAT_TYPES',
    'minecraft:recipe_book_category': 'RECIPE_BOOK_CATEGORIES',
    'minecraft:slot_display': 'SLOT_DISPLAYS',
    'minecraft:recipe_display': 'RECIPE_DISPLAYS',
    'minecraft:consume_effect_type': 'CONSUME_EFFECT_TYPES',
    'minecraft:map_decoration_type': 'MAP_DECORATION_TYPES',
    'minecraft:villager_profession': 'VILLAGER_PROFESSIONS',
    'minecraft:villager_type': 'VILLAGER_TYPES',
    'minecraft:position_source_type': 'POSITION_SOURCE_TYPES',
}


def entries(regs, reg):
    r = regs.get(reg, {})
    return {k: v['protocol_id'] for k, v in r.get('entries', {}).items()}, r.get('default')


w('/// Builtin registry ids, old -> new.')
w('pub mod registry {')
for reg, name in REMAPPED.items():
    o, _ = entries(registries_old, reg)
    n, default = entries(registries_new, reg)
    if not o:
        continue
    fallback = n.get(default, 0) if default else 0
    table = [0] * len(o)
    for k, i in o.items():
        table[i] = n.get(k, fallback)
    identical = all(table[i] == i for i in range(len(table))) and len(o) == len(n)
    w(f'    /// `{reg}` ({len(o)} -> {len(n)} entries).')
    w(f'    pub static {name}: [u16; {len(table)}] = {table};')
    w(f'    pub const {name}_IDENTICAL: bool = {"true" if identical else "false"};')
    w(f'    pub const {name}_NEW_LEN: usize = {len(n)};')
w('}')
w('')


def states(blocks):
    out = {}
    for name, b in blocks.items():
        for s in b['states']:
            out[(name, tuple(sorted(s.get('properties', {}).items())))] = s['id']
    return out


def default_state(blocks, name):
    for s in blocks.get(name, {}).get('states', []):
        if s.get('default'):
            return s['id']
    return 0


so, sn = states(blocks_old), states(blocks_new)
table = [0] * len(so)
for key, i in so.items():
    table[i] = sn.get(key, default_state(blocks_new, key[0]))
w(f'/// Block state ids, old -> new ({len(so)} -> {len(sn)}).')
w(f'pub static BLOCK_STATES: [u16; {len(table)}] = {table};')
w(f'pub const BLOCK_STATES_NEW_LEN: usize = {len(sn)};')
w('')

# Names the step refers to, in both versions.
NAMED = {
    'minecraft:item': 'item',
    'minecraft:data_component_type': 'component',
    'minecraft:entity_type': 'entity',
    'minecraft:particle_type': 'particle',
    'minecraft:sound_event': 'sound',
    'minecraft:menu': 'menu',
    'minecraft:block': 'block',
    'minecraft:consume_effect_type': 'consume_effect',
}
# Registries whose id -> name lists the step needs at runtime.
NAMES_FOR = {'minecraft:particle_type', 'minecraft:data_component_type'}
for reg, mod in NAMED.items():
    w(f'pub mod {mod} {{')
    for label, regs in (('old', registries_old), ('new', registries_new)):
        e, _ = entries(regs, reg)
        w(f'    pub mod {label} {{')
        for k, i in sorted(e.items(), key=lambda x: x[1]):
            w(f'        pub const {const(k)}: i32 = {i};')
        w(f'        pub const COUNT: i32 = {len(e)};')
        if reg in NAMES_FOR:
            names = [ident(k) for k, _ in sorted(e.items(), key=lambda x: x[1])]
            w(f'        pub static NAMES: [&str; {len(names)}] = {json.dumps(names)};')
        w('    }')
    w('}')
w('')

# Tags the new version has and the old lacks, for the builtin registries a
# server's tag ids can be resolved in. The ids are the new version's.
TAGGED = {'block': 'minecraft:block', 'item': 'minecraft:item', 'entity_type': 'minecraft:entity_type',
          'fluid': 'minecraft:fluid', 'game_event': 'minecraft:game_event'}


def tags(jar):
    out = {}
    for name in jar.namelist():
        if not name.startswith('data/minecraft/tags/') or not name.endswith('.json'):
            continue
        rest = name[len('data/minecraft/tags/'):-len('.json')]
        reg, _, path = rest.partition('/')
        if reg not in TAGGED:
            continue
        out.setdefault(reg, {})['minecraft:' + path] = json.loads(jar.read(name))['values']
    return out


tags_old, tags_new = tags(inner_jar(old_dir)), tags(inner_jar(new_dir))


def resolve(reg, tag, seen=()):
    ids = []
    for v in tags_new[reg].get(tag, []):
        required = True
        if isinstance(v, dict):
            v, required = v['id'], v.get('required', True)
        if v.startswith('#'):
            if v[1:] not in seen:
                ids += resolve(reg, v[1:], seen + (tag,))
        else:
            if ':' not in v:
                v = 'minecraft:' + v
            i = entries(registries_new, TAGGED[reg])[0].get(v)
            if i is not None:
                ids.append(i)
            elif required:
                raise SystemExit(f'unknown {reg} {v} in {tag}')
    return ids


w('/// Tags only the new version has: (registry, tag, new ids).')
w('pub static NEW_TAGS: &[(&str, &str, &[u16])] = &[')
for reg in TAGGED:
    for tag in sorted(set(tags_new.get(reg, {})) - set(tags_old.get(reg, {}))):
        ids = sorted(set(resolve(reg, tag)))
        w(f'    ("minecraft:{reg}", "{tag}", &{ids}),')
w('];')

os.makedirs(os.path.dirname(out_path), exist_ok=True)
with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(out) + '\n')
print(f'wrote {out_path}')
